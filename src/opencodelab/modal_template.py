from __future__ import annotations

import json

from opencodelab.config import Profile


def _py(value: str) -> str:
    return json.dumps(value)


def render_modal_app(profile: Profile) -> str:
    optional_args: list[str] = []
    if profile.language_model_only:
        optional_args.append('        "--language-model-only",')
    if profile.trust_remote_code:
        optional_args.append('        "--trust-remote-code",')
    if profile.speculative_mtp_tokens > 0:
        spec = json.dumps(
            {"method": "mtp", "num_speculative_tokens": profile.speculative_mtp_tokens},
            separators=(",", ":"),
        )
        optional_args.extend([
            '        "--speculative-config",',
            f"        {_py(spec)},",
        ])
    if profile.reasoning_parser:
        optional_args.extend([
            '        "--reasoning-parser",',
            f"        {_py(profile.reasoning_parser)},",
        ])
    if profile.tool_call_parser:
        optional_args.extend([
            '        "--enable-auto-tool-choice",',
            '        "--tool-call-parser",',
            f"        {_py(profile.tool_call_parser)},",
        ])

    optional = "\n".join(optional_args)
    if optional:
        optional += "\n"

    return f'''# Generated by OpenCodeLab. Do not edit; re-run `opencodelab setup` instead.
import os
import subprocess

import modal

MODEL_ID = {_py(profile.model_id)}
GPU = {_py(profile.gpu)}
MAX_MODEL_LEN = {profile.max_model_len}
IDLE_TIMEOUT_SECONDS = {profile.idle_timeout_seconds}
APP_NAME = {_py(profile.app_name)}
SECRET_NAME = {_py(profile.secret_name)}
VLLM_VERSION = {_py(profile.vllm_version)}
VLLM_PORT = 8000
MINUTES = 60

vllm_image = (
    modal.Image.from_registry(
        "nvidia/cuda:12.9.0-devel-ubuntu22.04",
        add_python="3.12",
    )
    .entrypoint([])
    .uv_pip_install(f"vllm=={{VLLM_VERSION}}")
    .env(
        {{
            "HF_XET_HIGH_PERFORMANCE": "1",
            "VLLM_LOG_STATS_INTERVAL": "5",
            "FLASHINFER_WORKSPACE_BASE": "/root/.cache/vllm",
            "TRITON_CACHE_DIR": "/root/.cache/vllm/triton",
        }}
    )
)

hf_cache = modal.Volume.from_name("opencodelab-huggingface-cache", create_if_missing=True)
vllm_cache = modal.Volume.from_name("opencodelab-vllm-cache", create_if_missing=True)
auth = modal.Secret.from_name(SECRET_NAME)
app = modal.App(APP_NAME)


@app.function(
    image=vllm_image,
    gpu=GPU,
    max_containers=1,
    scaledown_window=IDLE_TIMEOUT_SECONDS,
    timeout=20 * MINUTES,
    secrets=[auth],
    volumes={{
        "/root/.cache/huggingface": hf_cache,
        "/root/.cache/vllm": vllm_cache,
    }},
)
@modal.concurrent(max_inputs=1)
@modal.web_server(port=VLLM_PORT, startup_timeout=20 * MINUTES)
def serve():
    api_key = os.environ["OPENCODELAB_API_KEY"]
    cmd = [
        "vllm",
        "serve",
        MODEL_ID,
        "--served-model-name",
        MODEL_ID,
        "--host",
        "0.0.0.0",
        "--port",
        str(VLLM_PORT),
        "--api-key",
        api_key,
        "--dtype",
        "auto",
        "--gpu-memory-utilization",
        "0.92",
        "--max-model-len", str(MAX_MODEL_LEN),
        "--max-num-seqs",
        "1",
        "--max-num-batched-tokens",
        "2048",
        "--enable-prefix-caching",
{optional}    ]
    subprocess.Popen(cmd)
'''
